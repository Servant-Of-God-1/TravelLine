            jSpinner1.setEditor(khusus);
            setupSpinner("#,##0");
            jLabel4.setText("Biaya Operasional / 6 Bulan");
            // Gambar
            jLabel5.setIcon(new ImageIcon(getClass().getResource("/Image/InputPriceConfiguration/7.png")));
            jLabel2.setVisible(false);
            jLabel7.setVisible(false);
            jLabel8.setVisible(false);
